CREATE TABLE customization_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    selection_type VARCHAR(50) NOT NULL DEFAULT 'SINGLE', -- SINGLE, MULTI
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customization_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    price DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_option_group FOREIGN KEY (group_id) REFERENCES customization_groups(id) ON DELETE CASCADE
);

CREATE TABLE product_customization_groups (
    product_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    PRIMARY KEY (product_id, group_id),
    CONSTRAINT fk_pc_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT fk_pc_group FOREIGN KEY (group_id) REFERENCES customization_groups(id) ON DELETE CASCADE
);
